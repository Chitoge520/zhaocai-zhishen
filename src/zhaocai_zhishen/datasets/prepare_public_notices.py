from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path


KEYWORDS = {
    "信息化": ["信息化", "系统", "平台", "软件", "数据", "网络", "智能", "数字化", "运维"],
    "工程建设": ["工程", "建设", "施工", "改造", "维修", "安装"],
    "服务采购": ["服务", "管理", "运营", "维护", "配送", "培训"],
    "货物采购": ["设备", "家具", "电梯", "图书", "材料", "食材", "采购"],
}


def read_jsonl(path: Path) -> list[dict]:
    rows = []
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def normalize_text(value: object) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def infer_category(title: str, text: str) -> str:
    haystack = title + " " + text[:2000]
    scores = {}
    for category, words in KEYWORDS.items():
        scores[category] = sum(1 for word in words if word in haystack)
    best = max(scores.items(), key=lambda item: item[1])
    return best[0] if best[1] > 0 else "其他"


def estimate_has_tender_file(attachments: list[dict]) -> bool:
    for attachment in attachments:
        name = normalize_text(attachment.get("name"))
        url = normalize_text(attachment.get("url")).lower()
        if "招标文件" in name or "采购文件" in name:
            return True
        if any(ext in url for ext in (".doc", ".docx", ".zip", ".rar")):
            return True
    return False


def build_sample(row: dict, sample_id: int) -> dict:
    title = normalize_text(row.get("title"))
    text = normalize_text(row.get("text"))
    attachments = row.get("attachments") or []
    category = infer_category(title, text)
    has_tender_file = estimate_has_tender_file(attachments)
    return {
        "sample_id": f"public_notice_{sample_id:06d}",
        "source": "ccgp",
        "task_type": "public_notice_extraction",
        "title": title,
        "url": normalize_text(row.get("url")),
        "published_at": normalize_text(row.get("published_at")),
        "region": normalize_text(row.get("region")),
        "purchaser": normalize_text(row.get("purchaser")),
        "category": category,
        "has_attachment": bool(attachments),
        "has_tender_file": has_tender_file,
        "attachment_count": len(attachments),
        "attachment_names": "；".join(normalize_text(item.get("name")) for item in attachments),
        "html_path": normalize_text(row.get("html_path")),
        "text_length": len(text),
        "text_excerpt": text[:500],
        "label_level": "",
        "label_source": "",
        "label_reason": "",
    }


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = list(rows[0].keys()) if rows else [
        "sample_id",
        "source",
        "task_type",
        "title",
        "url",
        "published_at",
        "region",
        "purchaser",
        "category",
        "has_attachment",
        "has_tender_file",
        "attachment_count",
        "attachment_names",
        "html_path",
        "text_length",
        "text_excerpt",
        "label_level",
        "label_source",
        "label_reason",
    ]
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def prepare(input_path: Path, output_dir: Path) -> list[dict]:
    notices = read_jsonl(input_path)
    samples = [build_sample(row, index + 1) for index, row in enumerate(notices)]
    write_csv(output_dir / "public_notice_samples.csv", samples)
    write_jsonl(output_dir / "public_notice_samples.jsonl", samples)
    summary = {
        "input": str(input_path),
        "sample_count": len(samples),
        "with_attachment": sum(1 for sample in samples if sample["has_attachment"]),
        "with_tender_file": sum(1 for sample in samples if sample["has_tender_file"]),
        "categories": {},
    }
    for sample in samples:
        summary["categories"][sample["category"]] = summary["categories"].get(sample["category"], 0) + 1
    (output_dir / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    return samples


def main() -> None:
    parser = argparse.ArgumentParser(description="Prepare public notice samples for training data curation.")
    parser.add_argument("--input", required=True, help="Path to notices.jsonl generated by a collector.")
    parser.add_argument("--output", required=True, help="Output directory.")
    args = parser.parse_args()
    samples = prepare(Path(args.input), Path(args.output))
    print(f"Prepared {len(samples)} public notice samples into {args.output}")


if __name__ == "__main__":
    main()

